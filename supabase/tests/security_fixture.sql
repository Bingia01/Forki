CREATE ROLE anon;
CREATE ROLE authenticated;
CREATE ROLE service_role BYPASSRLS;
CREATE SCHEMA auth;
CREATE TABLE auth.users(id uuid PRIMARY KEY, email text, raw_user_meta_data jsonb);
CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$ SELECT nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
CREATE FUNCTION auth.role() RETURNS text LANGUAGE sql STABLE AS $$ SELECT current_setting('request.jwt.claim.role', true) $$;
GRANT USAGE ON SCHEMA auth TO anon, authenticated, service_role;
CREATE TABLE public.users(id uuid PRIMARY KEY, email text, name text);
CREATE TABLE public.user_preferences(user_id uuid PRIMARY KEY, daily_calorie_goal integer, weekly_calorie_goal integer);
CREATE TABLE public.food_logs(id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, user_id uuid NOT NULL, calories integer, logged_at timestamptz DEFAULT now());
CREATE TABLE public.user_progress(user_id uuid PRIMARY KEY, daily_progress numeric, weekly_progress numeric, last_updated timestamptz);
CREATE FUNCTION public.check_user_exists_in_auth(check_email text) RETURNS boolean LANGUAGE sql SECURITY DEFINER AS $$ SELECT EXISTS(SELECT 1 FROM auth.users WHERE email=check_email) $$;
CREATE FUNCTION public.handle_new_user() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER AS $$ BEGIN INSERT INTO public.users VALUES(NEW.id,NEW.email,NEW.raw_user_meta_data->>'name'); RETURN NEW; END $$;
CREATE FUNCTION public.set_meal_log_user_id() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER AS $$ BEGIN NEW.user_id=auth.uid(); RETURN NEW; END $$;
CREATE FUNCTION public.handle_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN NEW.updated_at=now(); RETURN NEW; END $$;
CREATE FUNCTION public.update_updated_at_column() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN NEW.updated_at=now(); RETURN NEW; END $$;
CREATE TRIGGER new_user AFTER INSERT ON auth.users FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();
GRANT SELECT,INSERT,UPDATE,DELETE ON public.food_logs TO authenticated,service_role;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA public TO authenticated,service_role;
GRANT SELECT ON public.user_progress TO authenticated,service_role;
ALTER TABLE public.food_logs ENABLE ROW LEVEL SECURITY;
CREATE POLICY own_food ON public.food_logs TO authenticated USING (user_id=auth.uid()) WITH CHECK (user_id=auth.uid());
